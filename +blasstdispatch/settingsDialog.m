function answer = settingsDialog(defaults)
%SETTINGSDIALOG Modal BLASST parameters with static, uneditable references.
%   ANSWER is a 1-by-9 cell array of strings, or {} when cancelled.
%   The two citations are plain MATLAB text controls, not input fields.
% SPDX-License-Identifier: Apache-2.0

if ~iscell(defaults) || numel(defaults) ~= 9 || ...
        ~all(cellfun(@(v) ischar(v) || (isstring(v) && isscalar(v)), defaults))
    error('BLASST:Dialog', 'Expected nine default setting strings.');
end

labels = { ...
    'Line frequencies (Hz; space-separated):', ...
    'Half-bandwidths (Hz; scalar or one per frequency):', ...
    'Gabor scale (seconds):', ...
    'Gabor resolution (integer):', ...
    'Maximum iterations:', ...
    'Channels (space-separated; blank for all):', ...
    'Core segment length (seconds; Inf=whole record):'};

eeGLABBackground = [0.66 0.76 1];
eeGLABForeground = [0 0 0.4];
eeGLABInputForeground = [0 0 0];
eeGLABButtonBackground = [0.93 0.96 1];
width = 715;
height = 820;
screen = get(0,'ScreenSize');
left = max(1, round(screen(1) + (screen(3)-width)/2));
bottom = max(1, round(screen(2) + (screen(4)-height)/2));
h = dialog('Name','BLASST Standalone v1.0.0', ...
    'Units','pixels','Position',[left bottom width height], ...
    'Resize','off','WindowStyle','modal', ...
    'Color',eeGLABBackground, ...
    'Tag','BLASSTStandaloneSettingsDialog', ...
    'CloseRequestFcn',@(src,event) blasstcore.finishSettingsDialog(src,event,false));
bg = eeGLABBackground;
edits = gobjects(1,7);
for k = 1:7
    y = height - 48 - (k-1)*67;
    uicontrol('Parent',h,'Style','text','String',labels{k}, ...
        'Units','pixels','Position',[20 y width-40 22], ...
        'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
        'FontSize',10);
    edits(k) = uicontrol('Parent',h,'Style','edit','String',char(defaults{k}), ...
        'Units','pixels','Position',[20 y-35 width-40 30], ...
        'BackgroundColor','white','ForegroundColor',eeGLABInputForeground, ...
        'HorizontalAlignment','left', ...
        'FontSize',10,'Tag',sprintf('BLASSTSetting%d',k));
end

% Parallelism is user-selectable, and requires no extra numeric field.
uicontrol('Parent',h,'Style','text','String','Execution mode:', ...
    'Units','pixels','Position',[20 285 width-40 22], ...
    'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10);
modePopup = uicontrol('Parent',h,'Style','popupmenu', ...
    'String',{'Serial','Parallel (Parallel Computing Toolbox)'}, ...
    'Units','pixels','Position',[20 251 width-40 30], ...
    'BackgroundColor','white','ForegroundColor',eeGLABInputForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10,'Tag','BLASSTExecutionMode');
if strcmpi(char(defaults{8}),'parallel')
    set(modePopup,'Value',2);
else
    set(modePopup,'Value',1);
end

% The two implementations are explicit, with the validated optimized
% candidate selected by default. 'Legacy' is the existing adapted port,
% NOT a claim of byte-for-byte identity with the public PREP source.
uicontrol('Parent',h,'Style','text','String','BLASST implementation:', ...
    'Units','pixels','Position',[20 210 width-40 22], ...
    'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10);
implementationPopup = uicontrol('Parent',h,'Style','popupmenu', ...
    'String',{'Optimized BLASST (default)', ...
              'Legacy BLASST (PREP-derived adapted port)'}, ...
    'Units','pixels','Position',[20 176 width-40 30], ...
    'BackgroundColor','white','ForegroundColor',eeGLABInputForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10,'Tag','BLASSTImplementation');
if strcmpi(char(defaults{9}),'legacy')
    set(implementationPopup,'Value',2);
else
    set(implementationPopup,'Value',1);
end

% A single citation heading, followed by two uneditable plain text rows.
% No extra entry boxes, labels such as "Validation", or visual frame.
uicontrol('Parent',h,'Style','text','String','Reference', ...
    'Units','pixels','Position',[20 128 width-40 21], ...
    'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
    'FontWeight','bold','FontSize',10,'Tag','BLASSTReferenceHeader');
uicontrol('Parent',h,'Style','text', ...
    'String','Ball et al. (2017), IEEE Trans Biomed Eng. DOI: 10.1109/TBME.2016.2632119', ...
    'Units','pixels','Position',[20 104 width-40 20], ...
    'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10,'Tag','BLASSTReferenceBall');
uicontrol('Parent',h,'Style','text', ...
    'String','Maruyama et al. (2026), Cortex. DOI: 10.1016/j.cortex.2026.11.005', ...
    'Units','pixels','Position',[20 80 width-40 20], ...
    'BackgroundColor',bg,'ForegroundColor',eeGLABForeground, ...
        'HorizontalAlignment','left', ...
    'FontSize',10,'Tag','BLASSTReferenceMaruyama');

uicontrol('Parent',h,'Style','pushbutton','String','OK', ...
    'Units','pixels','Position',[width-185 16 78 35], ...
    'BackgroundColor',eeGLABButtonBackground,'ForegroundColor',eeGLABForeground, ...
    'FontSize',10, ...
    'Callback',@(src,event) blasstcore.finishSettingsDialog(src,event,true));
uicontrol('Parent',h,'Style','pushbutton','String','Cancel', ...
    'Units','pixels','Position',[width-96 16 78 35], ...
    'BackgroundColor',eeGLABButtonBackground,'ForegroundColor',eeGLABForeground, ...
    'FontSize',10, ...
    'Callback',@(src,event) blasstcore.finishSettingsDialog(src,event,false));

setappdata(h,'BLASSTSettingsEdits',edits);
setappdata(h,'BLASSTExecutionModePopup',modePopup);
setappdata(h,'BLASSTImplementationPopup',implementationPopup);
setappdata(h,'BLASSTSettingsAccepted',false);
answer = {};
uiwait(h);
if ~isgraphics(h)
    return
end
if getappdata(h,'BLASSTSettingsAccepted')
    answer = arrayfun(@(editHandle) get(editHandle,'String'), edits, ...
        'UniformOutput',false);
    modes = {'serial','parallel'};
    answer{8} = modes{get(modePopup,'Value')};
    implementations = {'optimized','legacy'};
    answer{9} = implementations{get(implementationPopup,'Value')};
end
delete(h);
end
